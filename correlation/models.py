"""
correlation/models.py
=====================
ECHO — M3: Standard Data Models & Input/Output Interface.

Defines typed dataclasses for:
1. M1 Telemetry input (process & network)
2. M2 Detection signal input (ML, behavioural, resource)
3. Correlated process events
4. Risk score breakdowns
5. Policy decisions

This module acts as the public contract between M1, M2, M3, and M4.
"""

from dataclasses import dataclass, field, asdict
from typing import Optional, Dict, Any, List
import uuid
from datetime import datetime, timezone


def _utc_now_str() -> str:
    """Return ISO-8601 UTC timestamp string ending with Z."""
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f") + "Z"


@dataclass
class ProcessTelemetryInput:
    """
    Standard input schema for M1 process telemetry data.
    """
    pid: int
    process_name: str
    ppid: Optional[int] = None
    process_start_time: Optional[str] = None
    cpu_percent: float = 0.0
    memory_percent: float = 0.0
    memory_rss: Optional[int] = None
    open_sockets_count: int = 0
    distinct_remote_ips: int = 0
    num_threads: int = 1
    status: Optional[str] = "running"
    username: Optional[str] = None
    timestamp: Optional[str] = None
    host_id: Optional[str] = None
    event_id: Optional[str] = None

    def __post_init__(self):
        if not self.event_id:
            self.event_id = f"evt-{uuid.uuid4().hex[:12]}"
        if not self.timestamp:
            self.timestamp = _utc_now_str()
        if not self.process_start_time:
            self.process_start_time = self.timestamp

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class DetectionSignalInput:
    """
    Standard input schema for M2 detection outputs.
    Can accept either 0.0-1.0 or 0-100 normalized scores.
    """
    ml_anomaly_score: Optional[float] = None          # M: Isolation Forest / ML score
    ml_label: Optional[str] = None                    # e.g., 'anomaly', 'normal'
    behavioural_score: Optional[float] = None         # A: MAD / behavioural baseline score
    resource_anomaly_score: Optional[float] = None    # Q: Resource/network anomaly score
    is_simulated: bool = False                        # Explicit flag distinguishing simulated from live ML
    model_metadata: Optional[Dict[str, Any]] = None
    detection_timestamp: Optional[str] = None

    def __post_init__(self):
        if not self.detection_timestamp:
            self.detection_timestamp = _utc_now_str()

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class RiskScoreResult:
    """
    Detailed output of the Risk Engine calculation.
    """
    risk_score: float                                # 0.0 to 100.0
    risk_level: str                                  # 'low', 'medium', 'high', 'unknown'
    ml_score_normalized: Optional[float] = None      # 0.0 to 100.0
    behavioural_score_normalized: Optional[float] = None # 0.0 to 100.0
    resource_score_normalized: Optional[float] = None    # 0.0 to 100.0
    weights_used: Dict[str, float] = field(default_factory=dict)
    is_provisional: bool = False
    missing_signals: List[str] = field(default_factory=list)
    explanation: str = ""
    timestamp: str = field(default_factory=_utc_now_str)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


@dataclass
class CorrelatedSignal:
    """
    Correlated output combining M1 telemetry, M2 detections, and historical context.
    """
    correlation_id: str
    telemetry: ProcessTelemetryInput
    detection: DetectionSignalInput
    process_type_identity: str
    process_instance_identity: str
    repeated_observations_count: int = 1
    prior_anomaly_count: int = 0
    is_repeated_anomaly: bool = False
    parent_is_suspicious: bool = False
    timestamp: str = field(default_factory=_utc_now_str)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "correlation_id": self.correlation_id,
            "telemetry": self.telemetry.to_dict(),
            "detection": self.detection.to_dict(),
            "process_type_identity": self.process_type_identity,
            "process_instance_identity": self.process_instance_identity,
            "repeated_observations_count": self.repeated_observations_count,
            "prior_anomaly_count": self.prior_anomaly_count,
            "is_repeated_anomaly": self.is_repeated_anomaly,
            "parent_is_suspicious": self.parent_is_suspicious,
            "timestamp": self.timestamp,
        }


@dataclass
class PolicyDecision:
    """
    Structured policy outcome generated by M3 Policy Engine.
    """
    decision_id: str
    event_id: str
    pid: int
    process_name: str
    process_identity: str
    risk_score: float
    risk_level: str                                  # 'low', 'medium', 'high'
    recommended_action: str                          # 'alert', 'investigate', 'simulate_restriction', 'log_only', 'notify_operator'
    requires_approval: bool
    is_protected: bool
    reason: str
    timestamp: str = field(default_factory=_utc_now_str)
    context_metadata: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)

