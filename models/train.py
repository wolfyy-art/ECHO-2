"""
models/train.py
===============
ECHO — Phase 4 & 5: Model Training, Baseline Learning & Artifact Serialization
Author: Suhani (M2)

This script:
1. Generates synthetic multi-process host telemetry representing realistic
   workloads (Web service, File transfer, Background daemons).
2. Populates an ISOLATED database and CSV with the generated features.
3. Learns per-process statistical baselines (Median & MAD) via BehaviouralProfiler.
4. Fits the unsupervised Isolation Forest ensemble (100 trees, 13 features).
5. Serializes the trained model artifact to models/isolation_forest.joblib.
6. Writes training metadata to models/metadata.json.

SAFETY RULES
------------
- This script must NEVER write to the normal project database (data/echo.db).
- An explicit --db-path argument pointing to an isolated database is REQUIRED.
- The model artifact will NOT overwrite an existing file unless --force is supplied.
- All training data generated by this script is SYNTHETIC.  It does not represent
  real host telemetry.
"""

