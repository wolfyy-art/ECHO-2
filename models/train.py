# ---------------------------------------------------------------------------
# Synthetic telemetry generator
# ---------------------------------------------------------------------------

def generate_baseline_telemetry(n_windows: int = 40) -> pd.DataFrame:
    """
    Generate realistic multi-process baseline telemetry across discrete 5-second windows.

    Covers:
      - Process A: web_service (nginx / python web client)
      - Process B: file_transfer (rsync / backup daemon)
      - Process C (Normal Phase): background_worker
      - System daemons: cron, dbus-daemon, systemd-journald, sshd

    Returns
    -------
    pd.DataFrame
        Synthetic feature DataFrame matching the processed_features schema.
        All data is SYNTHETIC — it does not represent real host behaviour.
    """
    np.random.seed(42)
    rows: List[Dict[str, Any]] = []
    base_time = datetime.now(timezone.utc) - timedelta(seconds=n_windows * 5)

    process_specs = [
        # (name, pid, username, ppid, cpu_mean_range, mem_mb_range, threads, sockets, ips)
        ("nginx",             1010, "www-data",   1,    (1.0,  3.5),   (25.0,  35.0),  4, (3,  8),  (2, 5)),
        ("rsync_backup",      1020, "backup",     1,    (12.0, 24.0),  (80.0,  120.0), 3, (15, 30), (1, 3)),
        ("worker_daemon",     1030, "vboxuser",   1000, (0.2,  0.8),   (15.0,  20.0),  2, (0,  2),  (0, 1)),
        ("cron",               450, "root",       1,    (0.0,  0.1),   (3.0,   5.0),   1, (0,  0),  (0, 0)),
        ("dbus-daemon",        480, "messagebus", 1,    (0.1,  0.5),   (4.0,   6.0),   1, (1,  2),  (0, 0)),
        ("systemd-journald",   320, "root",       1,    (0.2,  1.0),   (18.0,  25.0),  1, (0,  0),  (0, 0)),
        ("sshd",               650, "root",       1,    (0.1,  0.4),   (6.0,   8.0),   1, (1,  3),  (1, 2)),
    ]

    for w_idx in range(n_windows):
        window_start = (base_time + timedelta(seconds=w_idx * 5)).strftime("%Y-%m-%dT%H:%M:%SZ")
        for name, pid, user, ppid, cpu_range, mem_range, threads, sock_range, ip_range in process_specs:
            cpu_m  = float(np.random.uniform(cpu_range[0], cpu_range[1]))
            cpu_mx = float(cpu_m + np.random.uniform(0.1, 1.5))
            cpu_s  = float(np.random.uniform(0.01, 0.5))
            mem_mb = float(np.random.uniform(mem_range[0], mem_range[1]))
            mem_pct = float(round((mem_mb / 4096.0) * 100.0, 3))
            mem_rss = int(mem_mb * 1024 * 1024)
            n_sockets = int(np.random.randint(sock_range[0], sock_range[1] + 1))
            n_ips     = int(np.random.randint(ip_range[0],   ip_range[1]   + 1))
            cpu_mem_ratio      = float(round(cpu_m    / max(mem_pct,  0.01), 4))
            socket_thread_ratio = float(round(n_sockets / max(threads, 1),   4))

            rows.append({
                "window_start":        window_start,
                "pid":                 pid,
                "ppid":                ppid,
                "process_name":        name,
                "username":            user,
                "status":              "running",
                "cpu_mean":            round(cpu_m,   2),
                "cpu_max":             round(cpu_mx,  2),
                "cpu_std":             round(cpu_s,   3),
                "memory_mean":         round(mem_pct, 3),
                "memory_max":          round(mem_pct * 1.05, 3),
                "memory_rss_mean":     mem_rss,
                "num_threads_mean":    float(threads),
                "num_threads_max":     threads,
                "open_sockets_count":  n_sockets,
                "distinct_remote_ips": n_ips,
                "sample_count":        5,
                "cpu_mem_ratio":       cpu_mem_ratio,
                "socket_thread_ratio": socket_thread_ratio,
            })

    return pd.DataFrame(rows)


# ---------------------------------------------------------------------------
# Database population
# ---------------------------------------------------------------------------

def populate_database_and_csv(
    df_features: pd.DataFrame,
    db_path: Path,
    output_csv: Path,
) -> None:
    """
    Store generated features into an ISOLATED SQLite database and CSV.

    Parameters
    ----------
    df_features : pd.DataFrame
        Synthetic feature records to persist.
    db_path : Path
        Path to the ISOLATED training database.  Must be supplied explicitly.
        This function will refuse to write to data/echo.db.
    output_csv : Path
        Output CSV path derived from the isolated database location.

    Raises
    ------
    ValueError
        If db_path resolves to the normal project database.
    """
    # Safety guard: refuse to write to the production database
    production_db = DB_PATH.resolve()
    if db_path.resolve() == production_db:
        raise ValueError(
            f"Training must not write to the production database at {production_db}. "
            f"Supply an isolated --db-path argument."
        )

    init_database(db_path)
    # Ensure the processed_features table exists in the isolated DB
    pipeline = PreprocessingPipeline(db_path=db_path)

    conn = _get_connection(db_path)
    try:
        with conn:
            for _, row in df_features.iterrows():
                conn.execute(
                    """
                    INSERT OR REPLACE INTO processed_features (
                        window_start, pid, ppid, process_name, username, status,
                        cpu_mean, cpu_max, cpu_std, memory_mean, memory_max,
                        memory_rss_mean, num_threads_mean, num_threads_max,
                        open_sockets_count, distinct_remote_ips, sample_count,
                        cpu_mem_ratio, socket_thread_ratio
                    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        row["window_start"], row["pid"], row["ppid"], row["process_name"],
                        row["username"], row["status"], row["cpu_mean"], row["cpu_max"],
                        row["cpu_std"], row["memory_mean"], row["memory_max"],
                        row["memory_rss_mean"], row["num_threads_mean"], row["num_threads_max"],
                        row["open_sockets_count"], row["distinct_remote_ips"], row["sample_count"],
                        row["cpu_mem_ratio"], row["socket_thread_ratio"],
                    ),
                )
        logger.info("Saved %d feature records into isolated SQLite 'processed_features'.", len(df_features))
    finally:
        conn.close()

    output_csv.parent.mkdir(parents=True, exist_ok=True)
    df_features.to_csv(output_csv, index=False)
    logger.info("Exported feature matrix to CSV: %s", output_csv)


# ---------------------------------------------------------------------------
# Model training and serialization
# ---------------------------------------------------------------------------

def train_and_serialize_models(
    df_features: pd.DataFrame,
    db_path: Path,
    model_file: Path = MODEL_FILE,
    metadata_file: Path = METADATA_FILE,
    output_csv: Path = None,
    force_overwrite: bool = False,
) -> Tuple[ProcessIsolationForest, Dict[str, Any]]:
    """
    Fit Isolation Forest and MAD Profiler using the ISOLATED database, then
    serialize artifacts.

    Parameters
    ----------
    df_features : pd.DataFrame
        Feature DataFrame (synthetic).
    db_path : Path
        ISOLATED database path.  Passed to BehaviouralProfiler so baselines
        are written to the same isolated database, not the production one.
    model_file : Path
        Output path for the serialized model artifact.
    metadata_file : Path
        Output path for the JSON metadata file.
    output_csv : Path
        Output path used in metadata for the features CSV.
    force_overwrite : bool
        If False (default) and model_file already exists, raises FileExistsError.

    Returns
    -------
    Tuple[ProcessIsolationForest, Dict[str, Any]]
        (trained_model, metadata_dict)

    Raises
    ------
    FileExistsError
        If model_file exists and force_overwrite is False.
    ValueError
        If db_path resolves to the production database.
    """
    # Safety guard: refuse to use the production database for baselines
    if db_path.resolve() == DB_PATH.resolve():
        raise ValueError(
            f"Training must not use the production database for baselines. "
            f"Supply an isolated --db-path argument."
        )

    # Artifact overwrite protection
    if model_file.exists() and not force_overwrite:
        raise FileExistsError(
            f"Model artifact already exists at {model_file}. "
            f"Use --force to overwrite, or choose a different output path."
        )

    MODELS_DIR.mkdir(parents=True, exist_ok=True)

    # 1. Learn MAD Behavioural Profiles — using the ISOLATED db_path
    logger.info("Computing per-process MAD baselines across %d records...", len(df_features))
    profiler = BehaviouralProfiler(db_path=db_path, model_version="1.0.0")
    baselines = profiler.learn_all_baselines(days=30.0)
    logger.info(
        "Generated and saved %d process baseline profiles into isolated 'process_baselines'.",
        len(baselines),
    )

    # 2. Fit Isolation Forest
    logger.info("Training Isolation Forest ensemble (n_estimators=100, contamination=0.05)...")
    config = IsolationForestConfig(n_estimators=100, random_state=42, contamination=0.05)
    model = ProcessIsolationForest(config=config)
    model.fit(df_features)

    # 3. Save Model Artifact (.joblib)
    saved_path = model.save(model_file)
    logger.info("Model artifact successfully serialized to: %s", saved_path)

    # 4. Save Metadata — explicitly mark data_source as "synthetic"
    csv_name = output_csv.name if output_csv else "process_features.csv"
    metadata = {
        "model_type":       "IsolationForest",
        "algorithm":        "scikit-learn.ensemble.IsolationForest",
        "version":          "1.0.0",
        "trained_at_utc":   _utc_now(),
        "data_source":      "synthetic",    # Always synthetic for this generator
        "training_samples": len(df_features),
        "unique_processes": int(df_features["process_name"].nunique()),
        "approved_features": list(APPROVED_FEATURE_COLUMNS),
        "hyperparameters":  config.to_dict(),
        "decision_offset":  float(model.score_offset_),
        "artifact_path":    str(model_file.name),
        "features_csv":     csv_name,
    }
    with open(metadata_file, "w", encoding="utf-8") as f:
        json.dump(metadata, f, indent=2)
    logger.info("Model metadata saved to: %s", metadata_file)

    return model, metadata


# ---------------------------------------------------------------------------
# CLI entry point
# ---------------------------------------------------------------------------

def main(argv: list = None) -> None:
    """
    Command-line entry point.  Requires --db-path to be explicitly supplied.
    Will not silently default to the production database.
    """
    parser = argparse.ArgumentParser(
        description=(
            "ECHO M2 — Synthetic Data Generation, Baseline Learning & ML Training. "
            "IMPORTANT: --db-path is required and must point to an ISOLATED database, "
            "not to data/echo.db."
        ),
    )
    parser.add_argument(
        "--db-path",
        type=Path,
        required=True,
        help=(
            "Path to an ISOLATED SQLite database for training data. "
            "Must NOT be data/echo.db.  Example: /tmp/echo_train.db"
        ),
    )
    parser.add_argument(
        "--windows",
        type=int,
        default=40,
        help="Number of 5-second synthetic telemetry windows to generate (default: 40).",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        default=False,
        help="Allow overwriting an existing model artifact.",
    )
    args = parser.parse_args(argv)

    db_path = args.db_path.resolve()

    # Refuse production database
    if db_path == DB_PATH.resolve():
        print(
            f"\nERROR: --db-path must not point to the production database ({DB_PATH}).\n"
            f"       Create an isolated path, e.g.:\n"
            f"         python models/train.py --db-path /tmp/echo_train.db\n",
            file=sys.stderr,
        )
        sys.exit(1)

    output_csv = db_path.parent / "process_features.csv"

    print("=" * 70)
    print(" ECHO M2: Synthetic Data Generation, Baseline Learning & ML Training")
    print("=" * 70)
    print(f" Isolated DB : {db_path}")
    print(f" Output CSV  : {output_csv}")
    print(f" Model File  : {MODEL_FILE}")
    print("=" * 70)

    # Step 1: Generate Synthetic Telemetry
    logger.info("[Step 1] Synthesizing multi-process baseline telemetry (%d windows)...", args.windows)
    df = generate_baseline_telemetry(n_windows=args.windows)

    # Step 2: Persist to Isolated Database
    logger.info("[Step 2] Storing synthetic telemetry in isolated SQLite and CSV...")
    populate_database_and_csv(df, db_path=db_path, output_csv=output_csv)

    # Step 3: Train and Serialize
    logger.info("[Step 3] Training ML Isolation Forest and computing MAD baselines...")
    model, metadata = train_and_serialize_models(
        df,
        db_path=db_path,
        output_csv=output_csv,
        force_overwrite=args.force,
    )

    # Step 4: Sanity Check
    sample_scores = model.score_samples(df.head(5))
    logger.info(
        "Sanity check on normal training samples — scores: %s (expected < 0.50 for normal)",
        sample_scores,
    )

    print("=" * 70)
    print(" Training Complete! Model and baselines are now available.")
    print(f" Model Artifact  : {MODEL_FILE}")
    print(f" Metadata        : {METADATA_FILE}")
    print(f" Data Source     : {metadata['data_source']}")
    print(f" Baselines       : {len(df['process_name'].unique())} profiles in isolated SQLite")
    print("=" * 70)


if __name__ == "__main__":
    main()
